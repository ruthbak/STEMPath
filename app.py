def load_roles():
    """
    Load and validate the O*NET-derived roles catalog from roles.json.

    The roles.json file is generated by import_onet_roles.py from raw
    O*NET data files. Each role must contain: id, title, category,
    description, and top_skills (as a list).

    Returns:
        list[dict]: List of validated role dictionaries.

    Raises:
        FileNotFoundError: If roles.json does not exist at DATA_DIR.
        ValueError: If any role is missing required keys or has an
                    invalid top_skills type.
    """
    if not ROLES_PATH.exists():
        raise FileNotFoundError(f"Could not find roles catalog at: {ROLES_PATH}")
    with open(ROLES_PATH, "r", encoding="utf-8") as f:
        roles = json.load(f)
    required_keys = {"id", "title", "category", "description", "top_skills"}
    for r in roles:
        missing = required_keys - set(r.keys())
        if missing:
            raise ValueError(f"Role '{r.get('id','UNKNOWN')}' missing keys: {missing}")
        if not isinstance(r["top_skills"], list):
            raise ValueError(f"Role '{r['id']}' top_skills must be a list")
    return roles


def find_role_by_id(role_id, roles):
    """
    Find a single role dict by its unique string ID.

    Args:
        role_id (str): The slugified role identifier (e.g. 'data_scientist').
        roles (list[dict]): The full roles catalog returned by load_roles().

    Returns:
        dict | None: The matching role dict, or None if not found.
    """
    return next((r for r in roles if r["id"] == role_id), None)


def normalize_skill(s):
    """
    Normalise a skill name for case-insensitive comparison.

    Args:
        s (str): Raw skill name string.

    Returns:
        str: Lowercase, stripped skill name.
    """
    return s.strip().lower()


def get_graph_skills():
    """
    Return the set of all skill names present in the Dijkstra graph.

    Collects all values from the 'teaches' and 'prerequisites' fields
    across every course/resource node in data.py. Used to determine
    which missing skills are pathfindable via Dijkstra vs unsupported.

    Returns:
        set[str]: All skill node names in the graph, excluding 'ROOT'.
    """
    supported = set()
    for c in courses:
        supported.update(c.get("teaches", []))
        supported.update(c.get("prerequisites", []))
    supported.discard("ROOT")
    return supported


def score_skill_gaps(missing_skills, all_roles):
    """
    Score each missing skill by its frequency across the entire roles catalog.

    Skills that appear in more roles have higher market demand and receive
    a higher market_score. This helps prioritise which gaps the user should
    address first.

    Scoring:
        market_score = (role_frequency / total_roles) * 100
        priority     = High (>=60%), Medium (>=30%), Low (<30%)

    Args:
        missing_skills (list[str]): Skills the user is missing for their target role.
        all_roles (list[dict]): Full roles catalog used to compute frequencies.

    Returns:
        list[dict]: List of scored skill dicts sorted by market_score descending.
                    Each dict contains: skill, market_score, priority.
    """
    frequency = {}
    for role in all_roles:
        for skill in role.get("top_skills", []):
            key = normalize_skill(skill)
            frequency[key] = frequency.get(key, 0) + 1
    total_roles = max(len(all_roles), 1)
    scored = []
    for skill in missing_skills:
        freq         = frequency.get(normalize_skill(skill), 0)
        market_score = round((freq / total_roles) * 100)
        priority     = "High" if market_score >= 60 else "Medium" if market_score >= 30 else "Low"
        scored.append({"skill": skill, "market_score": market_score, "priority": priority})
    return sorted(scored, key=lambda x: x["market_score"], reverse=True)


