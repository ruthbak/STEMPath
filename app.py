def extract_text_from_pdf(path):
    """
    Extract plain text from all pages of a PDF file.

    Args:
        path (str): Absolute path to the PDF file.

    Returns:
        str: Concatenated text content of all pages, separated by newlines.
    """
    text = []
    with pdfplumber.open(path) as pdf:
        for page in pdf.pages:
            text.append(page.extract_text() or "")
    return "\n".join(text)


def extract_text_from_docx(path):
    """
    Extract plain text from a Microsoft Word (.docx) document.

    Args:
        path (str): Absolute path to the .docx file.

    Returns:
        str: Concatenated text of all paragraphs, separated by newlines.
    """
    doc = Document(path)
    return "\n".join(p.text for p in doc.paragraphs)


def extract_skills_from_text(text, known_skills):
    """
    Identify STEM skills mentioned in a block of text using two-layer matching.

    Layer 1 — Direct match: checks whether any skill from known_skills
    appears as a whole word in the text.

    Layer 2 — Taxonomy match: checks BROAD_SKILL_TAXONOMY keyword lists
    to catch common aliases (e.g. 'matplotlib' → 'Data Visualization').

    Layer 3 — Noise filtering: removes skills that appear only once and
    are not surrounded by skills-related context words, reducing false
    positives from incidental mentions.

    Args:
        text (str): Raw text extracted from a resume or document.
        known_skills (list[str]): List of canonical skill names from roles.json.

    Returns:
        list[str]: Sorted list of identified skill names.
    """
    t = text.lower()
    found = set()
    for sk in known_skills:
        if re.search(r'\b' + re.escape(sk.lower()) + r'\b', t):
            found.add(sk)
    for skill_name, keywords in BROAD_SKILL_TAXONOMY.items():
        for kw in keywords:
            if re.search(r'\b' + re.escape(kw.lower()) + r'\b', t):
                found.add(skill_name)
                break
    weak = set()
    for skill in found:
        matches = list(re.finditer(r'\b' + re.escape(skill.lower()) + r'\b', t))
        if len(matches) == 1:
            position    = matches[0].start()
            surrounding = t[max(0, position-200):position+200]
            if not any(w in surrounding for w in ["skill", "technolog", "proficien", "experience", "language", "tool"]):
                weak.add(skill)
    found -= weak
    return sorted(found)


def parse_resume_for_skills(file_path, known_skills):
    """
    Parse a resume file (PDF or DOCX) and extract recognised STEM skills.

    Dispatches to the appropriate text extractor based on file extension,
    then passes the extracted text to extract_skills_from_text.

    Args:
        file_path (str): Absolute path to the uploaded resume file.
        known_skills (list[str]): Canonical skill names to match against.

    Returns:
        list[str]: Sorted list of skills found in the resume.
                   Returns an empty list for unsupported file types.
    """
    if file_path.lower().endswith(".pdf"):
        text = extract_text_from_pdf(file_path)
    elif file_path.lower().endswith(".docx"):
        text = extract_text_from_docx(file_path)
    else:
        return []
    found = extract_skills_from_text(text, known_skills)
    print("=== RESUME EXTRACTION ===")
    print("Text sample:", text[:300])
    print("Skills found:", found)
    return found


