def survey():
    """
    Generate and display a personalised skill proficiency survey.

    Uses the Groq LLM (llama-3.3-70b-versatile) to generate up to 6
    survey questions tailored to the user's degree, major, and skill gaps.
    Questions use a 1–5 Likert scale. Responses with a score >= 3 are
    treated as confirmed skills in survey_submit.

    If Groq fails or returns invalid JSON, questions defaults to [] and
    the user can skip the survey to proceed directly to results.

    Session keys written:
        survey_gaps — the list of gap skills used to generate questions
    """
    profile_data = get_latest_profile(session.get("user_id")) or session.get("profile")
    if profile_data:
        session["profile"] = profile_data
        session["active_profile_id"] = profile_data.get("id")
    if not profile_data:
        return redirect(url_for("profile"))

    selected_role_id = session.get("selected_role_id")
    role             = find_role_by_id(selected_role_id, load_roles()) if selected_role_id else None
    if not role:
        return redirect(url_for("roles"))

    questions, survey_meta, gaps = build_dynamic_survey_questions(profile_data, role)

    print("Survey claimed role skills:", survey_meta["claimed_target_count"])
    print("Survey gaps found:", gaps)
    print("Survey questions generated:", survey_meta["total"])

    session["survey_gaps"] = gaps
    session["survey_questions"] = questions
    return render_template(
        "survey.html",
        questions=questions,
        survey_meta=survey_meta,
        role=role,
        profile=profile_data,
    )


@app.route("/survey/submit", methods=["POST"])
@login_required
def survey_submit():
    """
    Process survey responses and update the user's confirmed skill list.

    Skills rated 3 or above (out of 5) are added to the user's profile
    skills, making them available for the skill gap calculation in /results.
    Redirects to the loading animation page which then redirects to /results.

    Session keys written:
        profile — updated with newly confirmed skills from the survey
    """
    profile_data = get_latest_profile(session.get("user_id")) or session.get("profile", {})
    survey_scores = []
    for key, score in request.form.items():
        if not key.startswith("score_") or not score.isdigit():
            continue
        index = key.replace("score_", "", 1)
        skill = request.form.get(f"skill_{index}", "").strip()
        reason = request.form.get(f"reason_{index}", "").strip()
        if skill:
            survey_scores.append({
                "skill": skill,
                "reason": reason,
                "score": int(score),
            })

    # Survey answers measure readiness/confidence. They do not mutate
    # confirmed profile skills, because that would erase the skill gap and
    # inflate the match score before the learner completes the roadmap.
    session["survey_scores"] = survey_scores
    session["profile"] = profile_data

    return redirect(url_for("loading"))


@app.route("/set-usertype", methods=["POST"])
def set_usertype():
    """Store the user's account type (student or professional) in the session."""
    session["user_type"] = request.form.get("user_type", "student")
    return redirect(url_for("roles"))


@app.get("/reset")
def reset():
    """
    Clear the user's current pathway data without logging them out.

    Removes profile, selected role, progress, and survey data from the
    session so the user can start a new career pathway from scratch.
    Auth session keys (user_id, display_name) are preserved.
    """
    session.pop("profile", None)
    session.pop("selected_role_id", None)
    session.pop("progress", None)
    session.pop("survey_gaps", None)
    session.pop("survey_scores", None)
    session.pop("survey_questions", None)
    session.pop("flash", None)
    session.pop("resume_notice", None)
    return redirect(url_for("roles"))


