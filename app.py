def fetch_youtube_videos(query, max_results=2):
    """
    Search YouTube Data API v3 and return video metadata.

    Requires the YOUTUBE_API_KEY environment variable to be set.
    Returns an empty list silently if the key is missing or the
    API call fails, so the rest of the results page still renders.

    Args:
        query (str): Search query string (e.g. 'Python for beginners').
        max_results (int): Maximum number of videos to return (default 2).

    Returns:
        list[dict]: List of video dicts, each containing:
                    title, url, thumbnail, video_id.
                    Returns [] if API key is absent or request fails.
    """
    api_key = os.environ.get("YOUTUBE_API_KEY", "")
    if not api_key:
        return []
    try:
        import urllib.parse
        q   = urllib.parse.quote(query)
        url = (
            f"https://www.googleapis.com/youtube/v3/search"
            f"?part=snippet&q={q}&type=video&maxResults={max_results}"
            f"&relevanceLanguage=en&key={api_key}"
        )
        with urllib.request.urlopen(url, timeout=5) as r:
            data = json.loads(r.read().decode())
        videos = []
        for item in data.get("items", []):
            vid_id = item["id"]["videoId"]
            title  = item["snippet"]["title"]
            thumb  = item["snippet"]["thumbnails"]["medium"]["url"]
            videos.append({
                "title":     title,
                "url":       f"https://www.youtube.com/watch?v={vid_id}",
                "thumbnail": thumb,
                "video_id":  vid_id,
                "embed_url": f"https://www.youtube.com/embed/{vid_id}",
            })
        return videos
    except Exception as e:
        print("YouTube API error:", e)
        return []


