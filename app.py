@app.post("/set-session")
def set_session():
    """
    Sync Firebase authentication state into the Flask server-side session.

    Called by base.html immediately after every Firebase login event
    (Google OAuth, email/password, or session restoration via
    onAuthStateChanged). Stores user_id and display_name so that
    @login_required decorators and server-side Jinja2 checks work correctly.

    Request body (JSON):
        user_id      (str): Firebase UID
        display_name (str): User's display name or email

    Returns:
        JSON: {"ok": True} on success.
    """
    data = request.get_json(silent=True) or {}
    user = upsert_user(
        data.get("user_id"),
        display_name=data.get("display_name"),
        email=data.get("email"),
        username=data.get("username"),
        user_type=data.get("user_type"),
    )

    display_name = (
        (user or {}).get("display_name")
        or data.get("display_name")
        or data.get("email")
    )

    session["user_id"]      = data.get("user_id")
    session["display_name"] = display_name

    existing_profile = get_latest_profile(data.get("user_id"))
    if existing_profile:
        session["profile"] = existing_profile
        session["active_profile_id"] = existing_profile["id"]

    selected_role_id = session.get("selected_role_id")
    existing_progress = get_progress(
        data.get("user_id"),
        profile_id=session.get("active_profile_id"),
        role_id=selected_role_id,
    )
    if existing_progress.get("skills"):
        session["progress"] = existing_progress

    if user:
        session["db_user_id"] = user["id"]
    return {
        "ok": True,
        "display_name": display_name,
        "email": (user or {}).get("email") or data.get("email"),
    }

@app.get("/logout")
def logout():
    """
    Clear the entire Flask session and redirect to the home page.

    Called when the user clicks Sign Out. Firebase sign-out is handled
    separately on the client side in base.html.
    """
    session.clear()
    return redirect(url_for("home"))


