def login_required(f):
    """
    Route decorator that redirects unauthenticated users to the home page.

    Checks for 'user_id' in the Flask session, which is set by the
    /set-session endpoint after a successful Firebase login. Any route
    decorated with @login_required will redirect to '/' if the user
    is not logged in.

    Args:
        f (function): The Flask view function to protect.

    Returns:
        function: The wrapped view function with auth check applied.
    """
    @wraps(f)
    def decorated(*args, **kwargs):
        if not session.get("user_id"):
            return redirect(url_for("home"))
        return f(*args, **kwargs)
    return decorated


